// Makes src/data/static/globeLand.ts: the dotted land of the Atlas globe (KAN-49/50).
// Data: Natural Earth 1:50m admin 0 countries (public domain, naturalearthdata.com).
// No library needed. Run once when the map data should change:
//   node scripts/make-globe-data.mjs path/to/ne_50m_admin_0_countries.geojson
// Download: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
import { readFileSync, writeFileSync } from 'node:fs';

const STEP = 2; // degrees between dots
const ROWS = 180 / STEP;
const COLS = 360 / STEP;

const file = process.argv[2];
if (!file) {
  console.error('Usage: node scripts/make-globe-data.mjs <ne_50m_admin_0_countries.geojson>');
  process.exit(1);
}
const geo = JSON.parse(readFileSync(file, 'utf8'));

/** ISO alpha-2, or "~~" for land without one (Natural Earth "-99"). */
const codeOf = (p) => {
  const c = p.ISO_A2_EH && p.ISO_A2_EH !== '-99' ? p.ISO_A2_EH : p.ISO_A2;
  return c && c !== '-99' ? c : '~~';
};

const shapes = geo.features.map((f) => {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  let minX = 180,
    maxX = -180,
    minY = 90,
    maxY = -90;
  for (const poly of polys)
    for (const [x, y] of poly[0]) {
      minX = Math.min(minX, x);
      maxX = Math.max(maxX, x);
      minY = Math.min(minY, y);
      maxY = Math.max(maxY, y);
    }
  return { code: codeOf(f.properties), polys, box: [minX, minY, maxX, maxY], p: f.properties };
});

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function inPoly(x, y, poly) {
  if (!inRing(x, y, poly[0])) return false;
  for (let h = 1; h < poly.length; h++) if (inRing(x, y, poly[h])) return false;
  return true;
}

const cells = [];
for (let r = 0; r < ROWS; r++) {
  const lat = 90 - STEP * (r + 0.5);
  for (let c = 0; c < COLS; c++) {
    const lng = -180 + STEP * (c + 0.5);
    let code = '..';
    for (const s of shapes) {
      const [a, b, cc, d] = s.box;
      if (lng < a || lng > cc || lat < b || lat > d) continue;
      if (s.polys.some((poly) => inPoly(lng, lat, poly))) {
        code = s.code;
        break;
      }
    }
    cells.push(code);
  }
}

// Run-length: "PT3" = 3 cells of Portugal, ".." = sea, "~~" = land without a code.
const runs = [];
for (let i = 0; i < cells.length;) {
  let n = 1;
  while (cells[i + n] === cells[i]) n++;
  runs.push(n === 1 ? cells[i] : `${cells[i]}${n}`);
  i += n;
}

// Label point per country (Natural Earth LABEL_X/Y): where the globe turns to, and the one dot
// of countries too small for the grid (Malta, Andorra, …).
const labels = {};
for (const s of shapes)
  if (s.code !== '~~' && !labels[s.code])
    labels[s.code] = [Math.round(s.p.LABEL_X * 10) / 10, Math.round(s.p.LABEL_Y * 10) / 10];

const out = `// Generated by scripts/make-globe-data.mjs from Natural Earth 1:50m countries (public domain).
// Do not edit by hand.

/** Degrees between two dots. Rows go from north to south, columns from 180° west to the east. */
export const GLOBE_STEP = ${STEP};
export const GLOBE_ROWS = ${ROWS};
export const GLOBE_COLS = ${COLS};

/** Run-length cells: two letters (ISO code, ".." sea, "~~" land without a code), then the count. */
export const GLOBE_RUNS =
  '${runs.join(' ')}';

/** [longitude, latitude] of each country's label point. */
export const COUNTRY_POINTS: Record<string, readonly [number, number]> = ${JSON.stringify(labels)};
`;
writeFileSync(new URL('../src/data/static/globeLand.ts', import.meta.url), out);
console.log(
  `Wrote ${runs.length} runs, ${cells.filter((c) => c !== '..').length} land dots, ${Object.keys(labels).length} countries.`,
);
